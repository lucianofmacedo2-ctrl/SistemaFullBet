/**
 * Normaliza um nome para busca no catálogo (remove acentos, pontuação e espaços extras)
 */
export function normalizeCatalogKey(name: string): string {
  return (name || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9\s-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Encontra a melhor URL de imagem oficial para um time
 */
export function findOfficialTeamLogo(teamName: string): string | undefined {
  const norm = normalizeCatalogKey(teamName);
  if (OFFICIAL_TEAM_LOGOS[norm]) return OFFICIAL_TEAM_LOGOS[norm];
  if (OFFICIAL_TEAM_LOGOS[teamName.toLowerCase().trim()]) return OFFICIAL_TEAM_LOGOS[teamName.toLowerCase().trim()];

  // Busca parcial
  for (const [k, url] of Object.entries(OFFICIAL_TEAM_LOGOS)) {
    const kNorm = normalizeCatalogKey(k);
    if (norm === kNorm || norm.startsWith(kNorm) || kNorm.startsWith(norm)) {
      return url;
    }
  }
  return undefined;
}

/**
 * Encontra a melhor URL de imagem oficial para uma liga
 */
export function findOfficialLeagueLogo(leagueName: string): string | undefined {
  const norm = normalizeCatalogKey(leagueName);
  if (OFFICIAL_LEAGUE_LOGOS[norm]) return OFFICIAL_LEAGUE_LOGOS[norm];
  if (OFFICIAL_LEAGUE_LOGOS[leagueName.toLowerCase().trim()]) return OFFICIAL_LEAGUE_LOGOS[leagueName.toLowerCase().trim()];

  // Busca parcial
  for (const [k, url] of Object.entries(OFFICIAL_LEAGUE_LOGOS)) {
    const kNorm = normalizeCatalogKey(k);
    if (norm === kNorm || norm.includes(kNorm) || kNorm.includes(norm)) {
      return url;
    }
  }
  return undefined;
}
